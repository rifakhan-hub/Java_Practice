package String;

import java.util.Arrays;

public class SortTheWord83 {
    public static void main(String[] args) {
        String s = " hello how are you doing ";

        // three steps 1.split 2. sort 3.join
        //step 1

































































































































































































































































































































































































































































































































        String word[] = s.split( " ");

        //bubble sort
        for(int i =0 ; i<word.length-1; i++){
            for (int j =0; j < word.length-1-i; j++){
                if(word[j].compareTo(word[j+1]) >0){
                    String t = word[j];
                    word [j] = word[j+1];
                    word[j+1]= t;

                }
            }
        }
        //  alternate method
        // Arrays.sort(word);

        s = String.join(" ", word);
        System.out.println(s);

    }
}
